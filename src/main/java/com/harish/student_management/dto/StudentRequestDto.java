package com.harish.student_management.dto;

import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Data;
import lombok.NoArgsConstructor;
import jakarta.validation.constraints.Email;
import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.Pattern;
import jakarta.validation.constraints.Size;

import java.time.LocalDate;

@Data
@NoArgsConstructor
@AllArgsConstructor
@Builder
public class StudentRequestDto {

    /** Backwards-compatible constructor retained for the original service tests. */
    public StudentRequestDto(String name, String email, String legacyCourse, String phone) {
        this.name = name;
        this.email = email;
        this.phone = phone;
    }

    /*
     * Admission number is generated by the backend.
     *
     * This field is intentionally kept for backwards compatibility with
     * existing edit requests / older clients, but it is NOT required
     * during student creation.
     *
     * StudentServiceImpl will ignore the value received from the client
     * and generate the admission number automatically.
     */
    private String admissionNo;

    @Size(max = 10, message = "Roll number must not exceed 10 characters")
    private String rollNumber;

    @NotBlank(message = "Name is required")
    @Size(min = 3, max = 100, message = "Name must be between 3 and 100 characters")
    private String name;

    @Size(max = 100, message = "Surname must not exceed 100 characters")
    private String surname;

    @Email(message = "Enter a valid email")
    private String email;

    @Pattern(
            regexp = "^[0-9]{10,15}$",
            message = "Phone number must be between 10 and 15 digits"
    )
    private String phone;

    private LocalDate dateOfBirth;

    @Size(max = 10, message = "Gender must not exceed 10 characters")
    private String gender;

    @Size(max = 5, message = "Blood group must not exceed 5 characters")
    private String bloodGroup;

    private LocalDate admissionDate;

    @Size(max = 255, message = "Address must not exceed 255 characters")
    private String address;

    private Long sectionId;

    private Long parentId;

    private Long academicYearId;

    @Size(max = 20, message = "Status must not exceed 20 characters")
    private String status;

    private Boolean transportRequired = false;
}